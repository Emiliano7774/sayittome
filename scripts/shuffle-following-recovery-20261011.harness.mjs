import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const {orderFollowingProfiles,followingStoryStatus}=await import(pathToFileURL(path.join(root,"src/lib/shuffle/followingStoryOrder.ts")).href);
const now=Date.now(),hour=3600000;
const profile=(uid,followedAtMs)=>({uid,username:uid,photo:"",showOnline:false,followedAtMs});
const followed=[profile("old",now-9*hour),profile("recent",now-hour),profile("newest",now-1000),profile("storyOld",now-10*hour),profile("storyNew",now-20*hour)];
const group=(uid,createdAtMs,expired=false)=>({ownerUid:uid,ownerUsername:uid,ownerPhoto:"",hasUnseen:true,stories:[{id:uid,ownerUid:uid,mediaType:"text",createdAtMs,expiresAtMs:expired?now-1000:now+hour,likeCount:0,viewCount:0}]});
const groups=[group("storyOld",now-2*hour),group("storyNew",now-1000)];
const ordered=orderFollowingProfiles(followed,groups,now).map(p=>p.uid);
assert.deepEqual(ordered,["storyNew","storyOld","newest","recent","old"],"fresh story then newest follow");
assert.deepEqual(orderFollowingProfiles(followed,[],now).map(p=>p.uid),["newest","recent","old","storyOld","storyNew"]);
assert.equal(followingStoryStatus(profile("storyNew",0),groups,now).hasUnseen,true);
assert.equal(followingStoryStatus(profile("storyNew",0),[group("storyNew",now-1000,true)],now).latestStoryAtMs,0,"expired stories demoted");
assert.equal(followingStoryStatus(profile("storyNew",0),[{...group("storyNew",now-1000),isAnonymousStory:true}],now).latestStoryAtMs,0,"anon author never relabeled registered follow");
const renamed=profile("auth-123",0);renamed.username="the.user";
const byName={...group("other-uid",now-100),ownerUsername:"THE.USER"};
assert.ok(followingStoryStatus(renamed,[byName],now).latestStoryAtMs>0,"story grouping alias can join by username");
assert.equal(orderFollowingProfiles([profile("a",0),profile("b",0)],[],now)[0].uid,"a","stable old follow tie");
const rules=fs.readFileSync(path.join(root,"firestore.rules"),"utf8");
assert.match(rules,/match \/usuarios\/\{uid\}[\s\S]*?match \/siguiendo\/\{targetUid\}\s*\{\s*allow get, list: if isOwner\(uid\);\s*allow create, update, delete: if false;/);
const hook=fs.readFileSync(path.join(root,"src/hooks/useFollowingProfiles.ts"),"utf8");
assert.match(hook,/collection\(db, "usuarios", uid, "siguiendo"\)/);
assert.match(hook,/Promise\.allSettled/);
assert.match(hook,/edgeTimestampMs\(data\.createdAt \|\| data\.updatedAt\)/);
const strip=fs.readFileSync(path.join(root,"src/components/shuffle/ClassicFollowingStrip.tsx"),"utf8");
assert.match(strip,/href=\{\`\/u\/\$\{encodeURIComponent\(profile\.username\)\}\`\}/);
assert.match(strip,/orderFollowingProfiles\(profiles, storyGroups\)/);
assert.match(strip,/subscribeStoriesIndex/);
assert.match(strip,/data-following-story/);
assert.match(strip,/getCachedStoryGroups\(\)/);
console.log(JSON.stringify({gate:"FOLLOWING_OWNER_READ_CHRONOLOGICAL_STORIES_REORDER",pass:true,checks:17}));
