import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const {shouldShowWebForegroundChatPush}=await import(pathToFileURL(path.join(root,"src/lib/chat/webForegroundPushPolicy.ts")).href);
const good={type:"chat_message",recipientUid:"recipient_A",chatId:"chat_a",messageId:"message_b",body:"hola"};
const accept=(data,viewerUid="recipient_A",ownMessage=false,enabled=true)=>shouldShowWebForegroundChatPush({data,viewerUid,ownMessage,enabled});
assert.equal(accept(good),true,"legitimate recipient data push");
assert.equal(accept({...good,recipientUid:"recipient_B"}),false,"cross-account push");
assert.equal(accept({...good,senderAuthUid:"recipient_A"}),false,"self author");
assert.equal(accept(good,"recipient_A",true),false,"locally sent doc id");
assert.equal(accept({...good,messageId:""}),false,"missing canonical message ID");
assert.equal(accept({...good,chatId:""}),false,"missing thread");
assert.equal(accept({...good,type:"anon_arrival"}),false,"different notification category");
assert.equal(accept(good,"recipient_A",false,false),false,"opted out");
assert.equal(accept({...good,inboxKind:"anon_direct"}),true,"direct anon peer receives push");
const fcm=read("src/lib/chat/fcmPush.ts");
assert.match(fcm,/onMessage\(getMessaging\(app\)/);
assert.match(fcm,/tryAlertIncomingMessage\(/);
assert.match(fcm,/isLocalOutgoingMessageId\(chatId, messageId\)/);
assert.match(fcm,/data\.inboxKind === "anon_direct"/);
assert.match(fcm,/await attachWebForegroundMessagingListener\(\)/);
const chat=read("src/components/chat/ProfileAnonChat.tsx");
const start=chat.indexOf("function chatMessagesSignature");
const signature=chat.slice(start,start+650);
assert.match(signature,/verifiedProfileAttestation/,"server attestation must invalidate React message signature");
assert.match(signature,/ticketId/);
assert.match(chat,/const loaded = mapFirestoreDocsToProfileAnonMessages\(/);
assert.match(read("src/lib/chat/profileAnonMessageAuthor.ts"),/verifiedProfileAttestation:\s*deletedForEveryone[\s\S]*?data\.verifiedProfileAttestation/);
const notification=read("src/lib/chat/chatNotifications.ts");
assert.match(notification,/input\.inboxKind === "anon_direct"/);
assert.match(read("public/chat-notify/sw.js"),/inboxKind:\s*String\(data\.inboxKind/);
assert.doesNotMatch(fcm,/\bgetDocs\s*\(/,"no extra Firestore reads");
assert.match(notification,/sayittome:web-foreground-push/,"page consumes SW foreground relay");
const sw=read("public/chat-notify/sw.js");
assert.match(sw,/self\.clients\.matchAll/);
assert.match(sw,/client\.visibilityState !== "visible"/);
assert.match(sw,/client\.postMessage/);
